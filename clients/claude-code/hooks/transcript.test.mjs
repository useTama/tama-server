import { expect, test } from "bun:test";
import { turnsFrom, projectFrom, shouldFile, trimToWire } from "./transcript.mjs";

/** A transcript line in the shape Claude Code actually writes. */
const line = (o) => JSON.stringify(o);
const user = (content, extra = {}) => line({ type: "user", message: { role: "user", content }, ...extra });
const asst = (content, extra = {}) => line({ type: "assistant", message: { role: "assistant", content }, ...extra });

test("only the conversation survives, not the tools", () => {
  // In a real session of any length, tool_use / tool_result / thinking / image
  // blocks outnumber text blocks about three to one. A summary written from
  // those describes the search instead of the conclusion.
  const turns = turnsFrom([
    user("why is the bridge crash-looping"),
    asst([{ type: "thinking", thinking: "let me look at the Dockerfile" }]),
    asst([{ type: "tool_use", name: "Bash", input: { command: "cat Dockerfile" } }]),
    user([{ type: "tool_result", content: "COPY bridge.mjs ..." }]),
    asst([{ type: "text", text: "The image never copied http-error.mjs." }]),
  ]);
  expect(turns).toEqual([
    { role: "user", text: "why is the bridge crash-looping" },
    { role: "assistant", text: "The image never copied http-error.mjs." },
  ]);
});

test("a subagent's turns are not the session's turns", () => {
  // A session that fanned out over twenty agents would otherwise be summarised
  // as twenty agents' conversations, none of which is the session.
  const turns = turnsFrom([
    user("triage every open issue"),
    user("you are triaging one open issue", { isSidechain: true }),
    asst([{ type: "text", text: "#67 is PARTLY_DONE" }], { isSidechain: true }),
    asst([{ type: "text", text: "Six are already done." }]),
  ]);
  expect(turns.map((t) => t.text)).toEqual(["triage every open issue", "Six are already done."]);
});

test("what the harness put in a user turn is not what the person typed", () => {
  const turns = turnsFrom([
    user("<system-reminder>\nCodebase instructions follow\n</system-reminder>"),
    user("<local-command-caveat>Caveat: the messages below</local-command-caveat>"),
    user("<command-name>/model</command-name>"),
    user("<bash-input>claude plugin install tama</bash-input>"),
    user("Caveat: The messages below were generated by the user"),
    user("push"),
  ]);
  expect(turns.map((t) => t.text)).toEqual(["push"]);
});

test("mixed text and tool blocks in one turn keep the text", () => {
  const turns = turnsFrom([
    asst([
      { type: "text", text: "Found it." },
      { type: "tool_use", name: "Edit", input: {} },
      { type: "text", text: "Fixing the COPY line." },
    ]),
  ]);
  expect(turns).toHaveLength(1);
  expect(turns[0].text).toBe("Found it.\nFixing the COPY line.");
});

test("a half-written last line is normal, not a failure", () => {
  // The transcript is appended to as the session runs and read the instant it
  // ends, so the tail can be a partial record.
  const turns = turnsFrom([user("hello"), '{"type":"assistant","message":{"content":[{"type":"te']);
  expect(turns.map((t) => t.text)).toEqual(["hello"]);
});

test("records that are neither user nor assistant are ignored", () => {
  const turns = turnsFrom([
    line({ type: "file-history-snapshot", snapshot: {} }),
    line({ type: "cost-state", totalCostUSD: 3.4 }),
    line({ type: "attachment", attachment: {} }),
    line({ type: "system", subtype: "hook" }),
    user("still here"),
  ]);
  expect(turns.map((t) => t.text)).toEqual(["still here"]);
});

test("the project is the directory the session ran in", () => {
  expect(projectFrom("/Users/shivansh/code/tama-server")).toBe("tama-server");
  expect(projectFrom("/Users/shivansh/code/tama-server/")).toBe("tama-server");
  expect(projectFrom("C:\\Users\\me\\code\\tama-server")).toBe("tama-server");
  expect(projectFrom("")).toBe("");
  expect(projectFrom(undefined)).toBe("");
});

test("resume is not an ending", () => {
  // Filing on resume writes an entry for work still going on, then writes
  // another when it actually finishes.
  expect(shouldFile("resume")).toBe(false);
  for (const reason of ["clear", "logout", "prompt_input_exit", "other", undefined]) {
    expect(shouldFile(reason)).toBe(true);
  }
});

test("the wire trim keeps both ends, like the server does", () => {
  // Trimming from the front drops the goal; trimming from the back drops the
  // outcome. A front slice at a fixed count is exactly the bug this pairs with
  // on the server: a 25MB session is ~500 turns, so slice(0, 400) discarded
  // the last ninety.
  const turns = [{ role: "user", text: "THE TASK" }];
  for (let i = 0; i < 900; i++) turns.push({ role: "assistant", text: "m".repeat(400) });
  turns.push({ role: "assistant", text: "THE OUTCOME" });

  const wire = trimToWire(turns);
  expect(wire[0].text).toBe("THE TASK");
  expect(wire.at(-1).text).toBe("THE OUTCOME");
  expect(wire.length).toBeLessThan(turns.length);
  expect(wire.reduce((n, t) => n + t.text.length, 0)).toBeLessThanOrEqual(120_000);
});

test("a short session goes over the wire untouched", () => {
  const turns = [
    { role: "user", text: "why is it broken" },
    { role: "assistant", text: "the COPY line" },
  ];
  expect(trimToWire(turns)).toEqual(turns);
  expect(trimToWire([])).toEqual([]);
});
